/**
 * Imprime el HTML de un ícono específico por su slug (con clases opcionales).
 */
function prcw_render_icon( $slug, $class = '' ) {
    $icons = prcw_get_icon_library();

    if ( ! isset( $icons[ $slug ] ) ) {
        return '';
    }

    $svg = $icons[ $slug ]['svg'];

    if ( $class ) {
        $svg = str_replace( '<svg ', '<svg class="' . esc_attr( $class ) . '" ', $svg );
    }

    return $svg;
}
